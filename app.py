import streamlit as st

# إعدادات صفحة الويب
st.set_page_title_config = st.set_page_config(
    page_title="Scinapse Agent - وكيل الأبحاث العلمية",
    page_icon="🔬",
    layout="wide"
)

# عنوان التطبيق الواجهة
st.title("🔬 Scinapse Agent: مساعدك الذكي للأبحاث العلمية")
st.markdown("""
مرحباً بكِ! هذا النظام مصمم لمساعدة الباحثين والطلاب في تحليل الأوراق البحثية، استخراج المعادلات، واكتشاف الفجوات العلمية باستخدام قوة **NVIDIA & Nebius AI**.
""")

# شريط جانبي لإدخال مفتاح الـ API أو إعدادات الوكيل
st.sidebar.header("إعدادات الوكيل ⚙️")
api_key = st.sidebar.text_input("أدخل مفتاح Nebius / NVIDIA API Key", type="password")

selected_task = st.sidebar.selectbox(
    "اختر مهمة الوكيل:",
    ["تلخيص وتصفية الأبحاث", "استخراج وشرح المعادلات الفيزيائية/الرياضية", "اكتشاف الفجوات البحثية الجديدة"]
)

# صندوق ادخال النص أو رفع الملفات
st.subheader("إدخال البيانات البحثية")
research_input = st.text_area("اكتب عنوان البحث، أو الصق ملخص الورقة البحثية هنا:", 
                             placeholder="مثال: دراسة سلوك الإلكترونات في المواد النانوية...")

uploaded_file = st.file_uploader("أو ارفع ملف الورقة البحثية (PDF):", type=["pdf", "txt"])

# زر التنفيذ
if st.button("تشغيل الوكيل الذكي 🚀"):
    if not api_key:
        st.warning("⚠️ الرجاء إدخال مفتاح الـ API في الشريط الجانبي أولاً.")
    elif not research_input and not uploaded_file:
        st.warning("⚠️ الرجاء كتابة نص البحث أو رفع ملف لتتمكن الوكلاء من تحليله.")
    else:
        with st.spinner("جاري معالجة البيانات وتحليلها بواسطة وكلاء الذكاء الاصطناعي..."):
            # محاكاة لعمل الوكيل (يمكنك ربطه بالـ API الفعلي لاحقاً)
            import time
            time.sleep(2)
            
            st.success("✨ تم إتمام التحليل بنجاح!")
            
            if selected_task == "تلخيص وتصفية الأبحاث":
                st.markdown("### 📄 ملخص النتائج والدراسات السابقة:")
                st.info("• تم استخراج 5 أبحاث ذات صلة وثيقة بموضوعك.\n• النقطة الأساسية المشتركة: زيادة كفاءة النقل الكمومي بنسبة 15%.\n• التوصية: التركيز على دراسة تأثير درجات الحرارة المرتفعة.")
                
            elif selected_task == "استخراج وشرح المعادلات الفيزيائية/الرياضية":
                st.markdown("### 🧮 المعادلات المستخرجة والشرح:")
                st.latex(r"i\hbar \frac{\partial}{\partial t} \psi = \hat{H} \psi")
                st.write("**شرح المعادلة:** تمثل معادلة شرودينجر الزمنية، وتُستخدم لتحديد كيف تغير الحالة الكمية للنظام مع مرور الوقت في سياق بحثك.")
                
            elif selected_task == "اكتشاف الفجوات البحثية الجديدة":
                st.markdown("### 💡 الفجوات المقترحة لأطروحتك القادمة:")
                st.success("1. لم تقم أي من الدراسات السابقة بقياس العامل الحركي تحت ضغط منخفض.\n2. توجد فرصة ممتازة لدمج نماذج التعلم الآلي للتنبؤ بسلوك الجسيمات بدلاً من الحسابات التقليدية.")

